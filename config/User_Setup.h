// 5. 可选微调（一般不用动，出问题再看）
// ---------------------------------------------------------------------------
// (1) 颜色反了：红蓝互换 → 去掉下行注释（1 = RGB，2 = BGR）
// #define TFT_RGB_ORDER 1
//
// (2) 颜色像底片一样反相（黑变白、白变黑）→ 二选一，去掉注释后重新编译：
// #define TFT_INVERSION_ON
// #define TFT_INVERSION_OFF
//
// (3) 屏幕四周有 1~2 像素黑边/图像偏移：少数 240x320 屏需要 CGRAM 偏移，
//     属于屏厂差异，遇到再查 docs\04_排错手册.md，不要乱加别的宏。
//
// (4) 不要定义 TOUCH_CS（本屏没有触摸），定义了库会去找触摸芯片，白等超时。
//
