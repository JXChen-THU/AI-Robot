/* ============================================================================
 *  AI-Robot · TFT_eSPI 配置文件  (ST7789  2.4 寸  240 x 320)
 *  适用板卡：ESP32-S3-DevKitC-1  N16R8
 *  版本    ：v1.0
 *  ---------------------------------------------------------------------------
 *  【这个文件是干什么的】
 *  TFT_eSPI 这个库不自带"你用的是哪块屏、接在哪几个脚"的信息，它启动时会去读
 *  一个叫 User_Setup.h 的配置文件。我们要做的就是把下面这一份，替换掉库自带的
 *  那一份，屏幕才能用正确的驱动芯片和正确的引脚点亮。
 *
 *  【怎么用（3 步，复制粘贴即可）】
 *  1) Arduino IDE → 左边"库管理器" → 搜索 TFT_eSPI → 安装 (作者 Bodmer)
 *  2) 找到这个库的安装位置，Windows 默认在：
 *        C:\Users\<你的用户名>\Documents\Arduino\libraries\TFT_eSPI\
 *     如果找不到这个目录：Arduino IDE → 文件 → 首选项 → 看"项目文件夹位置"，
 *     再到那个目录下面的 libraries\TFT_eSPI\ 就是。
 *     把本文件 (config\User_Setup.h) 复制过去，覆盖掉里面的同名文件 User_Setup.h
 *     （覆盖前可以先把它原来的 User_Setup.h 改名成 User_Setup.h.bak 留个后悔药）
 *  3) 关掉并重新打开 Arduino IDE（这一步别省，库的配置只在启动时读取），
 *     然后打开 firmware\01_display\01_display.ino 点"验证/上传"。
 *
 *  版本要求：TFT_eSPI 2.5.34 或更新（库管理器里装到的都是新版，直接装最新即可）。
 *
 *  【铁律：两份文件必须一模一样】
 *  本文件里的 4 个引脚号，必须和 firmware\_shared\pinmap.h 里的 PIN_TFT_* 完全一致。
 *  这个文件是**整个项目里唯一允许写数字引脚的地方**——因为 TFT_eSPI 是第三方库，
 *  它不认识我们的 pinmap.h。改引脚时要"两处一起改"：
 *        pinmap.h 的 PIN_TFT_SCL / SDA / CS / DC   ⇄   本文件的 TFT_SCLK / MOSI / CS / DC
 *  01_display.ino 里已经写了编译期检查：只要两边不一致，编译会直接报错并告诉你原因，
 *  不会让你烧进去看白屏。
 *  ---------------------------------------------------------------------------
 *  引脚对应关系（来自 docs\01_接线总表.md 第 3.2 节）：
 *      屏幕丝印        ESP32-S3        本文件宏
 *      ------------------------------------------------
 *      SCL / SCK       GPIO 21         TFT_SCLK
 *      SDA / MOSI      GPIO 47         TFT_MOSI
 *      CS              GPIO 3          TFT_CS
 *      DC / RS         GPIO 38         TFT_DC
 *      RES / RST       接 3V3          TFT_RST = -1  (不占 GPIO)
 *      BLK / LED       接 3V3          TFT_BL  = -1  (不占 GPIO，屏幕常亮)
 *      VCC             接 3V3          (白屏且确定线没问题，才可试 5V)
 *      GND             接 GND
 * ==========================================================================*/

// 给人看的名字，万一以后看串口诊断信息能认出来（可以不写，留着没坏处）
#define USER_SETUP_INFO "AI-Robot ST7789 240x320 (pins match firmware/_shared/pinmap.h)"

// ---------------------------------------------------------------------------
// 1. 驱动芯片 & 分辨率
// ---------------------------------------------------------------------------
#define ST7789_DRIVER
#define TFT_WIDTH  240
#define TFT_HEIGHT 320

// ---------------------------------------------------------------------------
// 2. 引脚（必须与 pinmap.h 一致！）
// ---------------------------------------------------------------------------
#define TFT_SCLK 21    // = PIN_TFT_SCL  屏幕 SCL
#define TFT_MOSI 47    // = PIN_TFT_SDA  屏幕 SDA
#define TFT_CS    3    // = PIN_TFT_CS   屏幕 CS
#define TFT_DC   38    // = PIN_TFT_DC   屏幕 DC

// RST 和 BLK 在硬件上直接插 3V3，不占用 GPIO，所以这里写 -1（-1 = 不用这个脚）
// 注意：TFT_RST 写 -1 时库会用"软复位"命令复位屏幕；TFT_BL 写 -1 时库不会去动背光。
// 千万不要把这两个改成真实引脚号，否则 01_display.ino 会直接编译报错提醒你。
#define TFT_RST -1
#define TFT_BL  -1

// 本屏没有 MISO/SDO（只用来看，不读取），显式写 -1 表示不占用这个脚。
// （不写也能编过，但写出来别人一眼就懂，省得以后有人以为漏配了。）
#define TFT_MISO -1

// ---------------------------------------------------------------------------
// 2.5 ★★ 非常重要：ESP32-S3 的 SPI 端口兼容开关（不用改，留着就对了）
// ---------------------------------------------------------------------------
// 现象：不写下面这一行，烧录后屏幕一直白屏/黑屏，串口大约每 1 秒刷一次
//       "Guru Meditation Error ... StoreProhibited" 然后重启，tft.init() 根本过不去。
//
// 原因（好奇再看，不看也没关系）：
//   TFT_eSPI 2.5.43（库管理器当前最新版）在 ESP32-S3 上默认用 FSPI 口，
//   但 Arduino-ESP32 core 2.0.15 之后（包括 3.x）的底层寄存器表里，
//   FSPI 对应的编号算出来是地址 0，于是库往地址 0x10 写数据 → 主控直接崩溃重启。
//   这是 TFT_eSPI 和 ESP32 core 之间的已知兼容问题（Bodmer 在 2026 年的代码里修了，
//   但还没发布新版本），社区通用解法就是把端口切到 HSPI。
//
// 打开下面这一行 = 改用 HSPI 口，屏幕就能正常点亮。这是社区大量 ESP32-S3 用户
// 验证过的写法，不是我们瞎猜的。
//   如果以后 TFT_eSPI 发布了修复版（2.5.44 或更新），屏幕反而白屏，可以试着
//   把这一行注释掉再编译；不确定就留着。
#define USE_HSPI_PORT

// ---------------------------------------------------------------------------
// 3. 字体
// ---------------------------------------------------------------------------
// LOAD_GLCD   : 最基础的 5x8 点阵英文字体（约 1.1KB Flash）。一定要留，否则中文注释
//               里的英文都没法显示，且多个示例依赖它。
#define LOAD_GLCD
// 下面两个是更大的英文字体，01_display.ino 里用来写标题和底部时间，留着显示更漂亮。
#define LOAD_FONT2     // 16px 高，底部运行时间用
#define LOAD_FONT4     // 26px 高，标题 "AI-Robot v1.0" 用
// 说明：以上三个都是 ASCII（英文/数字/符号），**没有中文字模**。
//       GLCD 只认 0~127 的 ASCII 码，中文会显示成空白或乱码，这是正常现象。
//
// 【想看中文怎么办？三选一】
//   (A) 本项目的 01_display.ino 已经自带 24x24 点阵，能把"桌面机器人"5 个汉字画出来
//       （数据直接写在代码里，不需要装字库，也不需要上传文件）——推荐，零成本。
//   (B) TFT_eSPI 的 SMOOTH_FONT + VLW 字库：显示任意中文、任意大小，但要把 .vlw 文件
//       上传到 ESP32 的 SPIFFS 文件系统里，小白第一次做容易卡住，暂不推荐。
//   (C) 干脆把界面文字写成英文，最省事，反正机器人表情基本不用字。
//
// ---------------------------------------------------------------------------
// 4. SPI 速度
// ---------------------------------------------------------------------------
// 默认 27MHz：杜邦线插拔、线长 10~20cm 的情况下最稳。
// 40MHz 也能跑（线短时），但零基础用户遇到花屏很难自己联想到"是速度问题"，
// 所以这里直接给保守值——27MHz 和 40MHz 在刷表情时肉眼几乎看不出区别。
// ★ 如果你的线特别短（<10cm）且想要更快的刷新率，可以试 40000000。
#define SPI_FREQUENCY 27000000

// 我们只往屏幕写，不读，所以读速度无所谓，给个稳妥值即可
#define SPI_READ_FREQUENCY 20000000

